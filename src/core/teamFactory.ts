export const coachName = (rng: Rng) => `${rng.pick(COACH_FIRST)} ${rng.pick(COACH_LAST)}`;

/**
 * A new coach: his name, development and in-game skills, and his style (a real team's with some of his
 * own on it: see randomStyle), with his playbooks named for the ones nearest it.
 */
export function randomCoach(rng: Rng): CoachProfile {
  const name = coachName(rng);
  // (the style comes from a stream of its own, seeded by the two draws his playbooks were once picked
  // with: the league's stream moves exactly as it did)
  const seed = (Math.floor(rng.next() * 4294967296) ^ Math.floor(rng.next() * 65536)) >>> 0;
  const development = Math.round(rng.uniform(35, 85));
  const tactics = Math.round(rng.uniform(35, 85));
  const style = randomStyle(new Rng(seed));
  return { name, offPhilosophy: nearestOffPreset({ ...style, threePoint: style.threePoint }), defPhilosophy: defPresetOf(style.coverage, style.zone), development, tactics, style };
}

export function emptyTotals(): TeamTotals {
  return { fgm: 0, fga: 0, tpm: 0, tpa: 0, ftm: 0, fta: 0, orb: 0, drb: 0, ast: 0, stl: 0, blk: 0, tov: 0, pf: 0, pts: 0 };
}

export function newTeamSeason(season: number, pop: number): TeamSeason {
  return {
    season,
    won: 0,
    lost: 0,
    homeWon: 0,
    homeLost: 0,
    confWon: 0,
    confLost: 0,
    divWon: 0,
    divLost: 0,
    streak: 0,
    lastTen: [],
    ptsFor: 0,
    ptsAgainst: 0,
    poss: 0,
    oppPoss: 0,
    playoffRound: -1,
    seed: null,
    revenue: 0,
    expenses: 0,
    payroll: 0,
    attendance: 0,
    pop,
    t: emptyTotals(),
    o: emptyTotals(),
  };
}

export function makeTeam(tid: number, season: number, rng: Rng): Team {
  const f = FRANCHISES[tid];
  const coach = randomCoach(rng);
  return {
    tid,
    abbrev: f.abbrev,
    region: f.region,
    name: f.name,
    // a copy: the franchise table is shared by every league
    colors: [...f.colors],
    conf: f.conf,
    div: f.div,
    pop: f.pop,
    tactics: defaultTactics(coach.offPhilosophy, coach.defPhilosophy),
    rotation: { order: [], minutes: {}, closers: [], restB2B: [], caps: {}, manual: false },
    strategy: 'retool',
    budget: { coaching: 50, health: 50, facilities: 50, ticketPrice: 95 },
    cash: 60_000,
    hype: 0.5,
    coach,
    seasons: [newTeamSeason(season, f.pop)],
    deadMoney: [],
    practice: 'normal',
  };
}
